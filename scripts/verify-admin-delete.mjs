async function actor(role, appRole, sub = adminId, extra = {}) {
  await db.exec('reset role');
  const jwt = JSON.stringify({ role, sub, app_metadata: { role: appRole }, ...extra });
  await db.query("select set_config('request.jwt.claims', $1, false)", [jwt]);
  await db.exec(`set role ${role}`);
}
async function denied(sql, params = []) {
  await assert.rejects(db.query(sql, params), e => e.code === '42501');
  checks++;
}
async function rpc(name, value) {
  const { rows } = await db.query(`select public.${name}($1) as result`, [value]);
  return rows[0].result;
}
async function count(table) {
  await db.exec('reset role');
  const { rows } = await db.query(`select count(*)::int as n from public.${table}`);
  return rows[0].n;
}

