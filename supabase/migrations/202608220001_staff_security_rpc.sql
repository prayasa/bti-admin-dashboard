-- ============================================================
-- PASSWORD HASHING
-- ============================================================

create or replace function public.bti_hash_teknisi_password()
returns trigger
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $function$
begin
    if new.password is null
       or btrim(new.password) = '' then
        raise exception
            'Password teknisi tidak boleh kosong.'
            using errcode = 'P0001';
    end if;

    if new.password
       !~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$' then
        new.password := crypt(
            new.password,
            gen_salt('bf', 12)
        );
    end if;

    return new;
end;
$function$;

drop trigger if exists
    trg_bti_hash_teknisi_password
on public.teknisi;

create trigger trg_bti_hash_teknisi_password
before insert or update of password
on public.teknisi
for each row
execute function public.bti_hash_teknisi_password();


-- Mengubah password plaintext lama menjadi bcrypt.

update public.teknisi
