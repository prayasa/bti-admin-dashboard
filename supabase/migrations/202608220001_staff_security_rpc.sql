-- ============================================================
-- RPC 3: HOME
--
-- Android response:
-- total_assignments
-- pending_assignments
-- in_progress_assignments
-- completed_assignments
-- last_attendance
-- recent_assignments
-- ============================================================

create or replace function public.staff_get_home(
    p_technician_id text,
    p_device_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $function$
declare
    v_staff public.teknisi%rowtype;

    v_total_assignments bigint;
    v_pending_assignments bigint;
    v_in_progress_assignments bigint;
    v_completed_assignments bigint;

    v_last_attendance jsonb;
    v_recent_assignments jsonb;
begin
    select *
    into v_staff
    from public.bti_require_staff_device(
        p_technician_id,
        p_device_id
    );

    select
        count(*),
        count(*) filter (
            where t.status = 'Pending'
        ),
        count(*) filter (
            where t.status = 'On Process'
        ),
        count(*) filter (
            where t.status = 'Success'
        )
    into
        v_total_assignments,
        v_pending_assignments,
        v_in_progress_assignments,
        v_completed_assignments
    from public.tiket_tugas as t
    where t.id_teknisi = v_staff.id;

    select jsonb_build_object(
        'id_absen',
        l.id_absen::text,
        'tipe_log',
        l.tipe_log,
        'waktu_log',
        l.waktu_log,
        'latitude_aktual',
        l.latitude_aktual,
        'longitude_aktual',
        l.longitude_aktual,
        'is_valid',
        l.is_valid
    )
    into v_last_attendance
    from public.log_presensi as l
    where l.id_teknisi = v_staff.id
    order by
        l.waktu_log desc,
        l.id_absen desc
    limit 1;

    select coalesce(
        jsonb_agg(
            assignment_item
            order by assignment_created_at desc
        ),
        '[]'::jsonb
    )
    into v_recent_assignments
    from (
        select
            jsonb_build_object(
                'id',
                t.id_tugas::text,
                'id_tugas',
                t.id_tugas::text,
                'nama_klien',
                t.nama_klien,
                'alamat_klien',
                t.alamat_klien,
                'status',
                t.status,
                'created_at',
                t.created_at
            ) as assignment_item,
            t.created_at as assignment_created_at
        from public.tiket_tugas as t
        where t.id_teknisi = v_staff.id
        order by t.created_at desc
        limit 5
    ) as recent_rows;

    return jsonb_build_object(
        'total_assignments',
        coalesce(v_total_assignments, 0),
        'pending_assignments',
        coalesce(v_pending_assignments, 0),
        'in_progress_assignments',
        coalesce(v_in_progress_assignments, 0),
        'completed_assignments',
        coalesce(v_completed_assignments, 0),
        'last_attendance',
        coalesce(
            v_last_attendance,
            '{}'::jsonb
        ),
        'recent_assignments',
        coalesce(
            v_recent_assignments,
            '[]'::jsonb
        )
    );
end;
$function$;


