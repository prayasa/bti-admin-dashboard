-- ============================================================
-- RPC 5: UPDATE ASSIGNMENT STATUS
--
-- Android request:
-- p_technician_id
-- p_device_id
-- p_assignment_id
-- p_new_status
-- ============================================================

create or replace function
public.staff_update_assignment_status(
    p_technician_id text,
    p_device_id text,
    p_assignment_id text,
    p_new_status text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $function$
declare
    v_staff public.teknisi%rowtype;
    v_assignment public.tiket_tugas%rowtype;
    v_assignment_id text;
    v_new_status text;
begin
    select *
    into v_staff
    from public.bti_require_staff_device(
        p_technician_id,
        p_device_id
    );

    v_assignment_id := nullif(
        btrim(coalesce(p_assignment_id, '')),
        ''
    );

    v_new_status :=
        case lower(
            btrim(coalesce(p_new_status, ''))
        )
            when 'on process'
                then 'On Process'
            when 'success'
                then 'Success'
            else null
        end;

    if v_assignment_id is null then
        raise exception
            'ID penugasan tidak valid.'
            using errcode = 'P0001';
    end if;

    if v_new_status is null then
        raise exception
            'Status tujuan tidak didukung.'
            using errcode = 'P0001';
    end if;

    select t.*
    into v_assignment
    from public.tiket_tugas as t
    where t.id_tugas::text = v_assignment_id
      and t.id_teknisi = v_staff.id
    for update;

    if not found then
        raise exception
            'Penugasan tidak ditemukan atau bukan milik akun ini.'
            using errcode = 'P0001';
    end if;

    if v_assignment.status = 'Success' then
        return jsonb_build_object(
            'success',
            false,
            'accepted',
            false,
            'message',
            'Penugasan yang sudah selesai tidak dapat diubah kembali.'
        );
    end if;

    if v_assignment.status = 'Pending'
       and v_new_status = 'Success' then
        return jsonb_build_object(
            'success',
            false,
            'accepted',
            false,
            'message',
            'Penugasan harus diproses terlebih dahulu sebelum diselesaikan.'
        );
    end if;

    if v_assignment.status = 'On Process'
       and v_new_status = 'On Process' then
        return jsonb_build_object(
            'success',
            true,
            'accepted',
            true,
            'message',
            'Penugasan sudah berstatus On Process.',
            'status',
            v_assignment.status
        );
    end if;

    update public.tiket_tugas
    set status = v_new_status
    where id_tugas = v_assignment.id_tugas
      and id_teknisi = v_staff.id
    returning *
    into v_assignment;

    return jsonb_build_object(
        'success',
        true,
        'accepted',
        true,
        'message',
        'Status penugasan berhasil diperbarui.',
        'id',
        v_assignment.id_tugas::text,
        'id_tugas',
        v_assignment.id_tugas::text,
        'status',
        v_assignment.status
    );
end;
$function$;


-- ============================================================
-- RPC 6: ATTENDANCE HISTORY
--
-- Android request:
-- p_technician_id
-- p_device_id
-- p_start_at
-- p_end_at
-- p_limit
-- ============================================================

create or replace function public.staff_get_attendance(
    p_technician_id text,
    p_device_id text,
    p_start_at text,
    p_end_at text,
    p_limit integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $function$
declare
    v_staff public.teknisi%rowtype;
    v_start_at timestamp with time zone;
    v_end_at timestamp with time zone;
    v_end_exclusive boolean := false;
    v_limit integer;
    v_records jsonb;
begin
    select *
    into v_staff
    from public.bti_require_staff_device(
        p_technician_id,
        p_device_id
    );

    v_limit := greatest(
        1,
        least(
            coalesce(p_limit, 30),
            100
        )
    );

    if nullif(
        btrim(coalesce(p_start_at, '')),
        ''
    ) is not null then
        begin
            if btrim(p_start_at)
               ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' then
                v_start_at := (
                    btrim(p_start_at)::date::timestamp
                    at time zone 'Asia/Pontianak'
                );
            else
                v_start_at :=
                    btrim(p_start_at)::timestamp with time zone;
            end if;
        exception
            when others then
                raise exception
                    'Format tanggal awal tidak valid.'
                    using errcode = 'P0001';
        end;
    end if;

    if nullif(
        btrim(coalesce(p_end_at, '')),
        ''
    ) is not null then
        begin
            if btrim(p_end_at)
               ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' then
                v_end_at := (
                    (
                        btrim(p_end_at)::date + 1
                    )::timestamp
                    at time zone 'Asia/Pontianak'
                );

                v_end_exclusive := true;
            else
                v_end_at :=
                    btrim(p_end_at)::timestamp with time zone;

                v_end_exclusive := false;
            end if;
        exception
            when others then
                raise exception
                    'Format tanggal akhir tidak valid.'
                    using errcode = 'P0001';
        end;
    end if;

    if v_start_at is not null
       and v_end_at is not null
       and v_start_at >= v_end_at then
        raise exception
            'Rentang tanggal presensi tidak valid.'
            using errcode = 'P0001';
    end if;

    select coalesce(
        jsonb_agg(
            attendance_item
            order by attendance_time desc
        ),
        '[]'::jsonb
    )
    into v_records
    from (
        select
            jsonb_build_object(
                'id',
                l.id_absen::text,
                'id_absen',
                l.id_absen::text,
                'tipe_log',
                l.tipe_log,
                'waktu_log',
                l.waktu_log,
                'latitude_aktual',
                l.latitude_aktual,
                'longitude_aktual',
                l.longitude_aktual,
                'is_valid',
                l.is_valid
            ) as attendance_item,
            l.waktu_log as attendance_time
        from public.log_presensi as l
        where l.id_teknisi = v_staff.id
          and (
                v_start_at is null
                or l.waktu_log >= v_start_at
              )
          and (
                v_end_at is null
                or (
                    v_end_exclusive
                    and l.waktu_log < v_end_at
                )
                or (
                    not v_end_exclusive
                    and l.waktu_log <= v_end_at
                )
              )
        order by
            l.waktu_log desc,
            l.id_absen desc
        limit v_limit
    ) as attendance_rows;

    return v_records;
end;
$function$;


-- ============================================================
-- RPC 7: SUBMIT ATTENDANCE
--
-- Android request:
-- p_technician_id
-- p_device_id
-- p_attendance_type
-- p_qr_payload
-- p_latitude
-- p_longitude
-- p_accuracy_meters
-- p_location_age_ms
-- p_is_mock
--
-- Android response:
-- accepted
-- message
-- ============================================================

create or replace function public.staff_submit_attendance(
    p_technician_id text,
    p_device_id text,
    p_attendance_type text,
    p_qr_payload text,
    p_latitude double precision,
    p_longitude double precision,
    p_accuracy_meters double precision,
    p_location_age_ms bigint,
    p_is_mock boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $function$
declare
    v_staff public.teknisi%rowtype;
    v_config public.bti_mobile_config%rowtype;

    v_attendance_type text;
    v_qr_payload text;
    v_qr_uuid text;
    v_qr_time_text text;
    v_qr_time_ms bigint;
    v_active_qr_token text;

    v_server_time_ms bigint;
    v_qr_age_ms bigint;
    v_distance_meters double precision;

    v_last_today_type text;
    v_claimed_count integer;

    v_attendance_id text;
    v_attendance_time timestamp with time zone;
begin
    select *
    into v_staff
    from public.bti_require_staff_device(
        p_technician_id,
        p_device_id
    );

    select c.*
    into v_config
    from public.bti_mobile_config as c
    where c.id = 1;

    if not found then
        raise exception
            'Konfigurasi aplikasi mobile belum tersedia.'
            using errcode = 'P0001';
    end if;

    v_attendance_type := upper(
        btrim(coalesce(p_attendance_type, ''))
    );

    v_qr_payload := btrim(
        coalesce(p_qr_payload, '')
    );

    if v_attendance_type not in (
        'MASUK',
        'PULANG'
    ) then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Jenis presensi tidak valid.'
        );
    end if;

    if p_is_mock is null
       or p_is_mock then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Lokasi palsu atau mock location terdeteksi.'
        );
    end if;

    if p_latitude is null
       or p_longitude is null
       or p_latitude < -90
       or p_latitude > 90
       or p_longitude < -180
       or p_longitude > 180 then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Koordinat lokasi tidak valid.'
        );
    end if;

    if p_accuracy_meters is null
       or p_accuracy_meters < 0
       or p_accuracy_meters >
          v_config.max_location_accuracy_meters then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Akurasi lokasi belum memenuhi batas yang diizinkan.'
        );
    end if;

    if p_location_age_ms is null
       or p_location_age_ms < 0 then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Usia data lokasi tidak valid.'
        );
    end if;

    if p_location_age_ms >
       v_config.max_location_age_ms then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Data lokasi sudah terlalu lama. Perbarui lokasi dan coba kembali.'
        );
    end if;

    if v_qr_payload = ''
       or array_length(
            string_to_array(
                v_qr_payload,
                '|'
            ),
            1
          ) <> 2 then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Format QR Code tidak valid.'
        );
    end if;

    v_qr_uuid := split_part(
        v_qr_payload,
        '|',
        1
    );

    v_qr_time_text := split_part(
        v_qr_payload,
        '|',
        2
    );

    if v_qr_uuid
       !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
       or v_qr_time_text
          !~ '^[0-9]{10,16}$' then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Format token QR Code tidak valid.'
        );
    end if;

    begin
        v_qr_time_ms :=
            v_qr_time_text::bigint;
    exception
        when invalid_text_representation
          or numeric_value_out_of_range then
            return public.bti_reject_attendance_request(
                v_staff.id::text,
                p_device_id,
                v_attendance_type,
                v_qr_payload,
                p_latitude,
                p_longitude,
                p_accuracy_meters,
                p_location_age_ms,
                null,
                p_is_mock,
                'Waktu token QR Code tidak valid.'
            );
    end;

    v_server_time_ms := floor(
        extract(
            epoch from clock_timestamp()
        ) * 1000
    )::bigint;

    v_qr_age_ms :=
        v_server_time_ms -
        v_qr_time_ms;

    if v_qr_age_ms <
       -v_config.qr_future_tolerance_ms then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Token QR Code berasal dari waktu yang tidak valid.'
        );
    end if;

    if v_qr_age_ms >
       v_config.qr_max_age_ms then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Token QR Code sudah kedaluwarsa.'
        );
    end if;

    select to_jsonb(q) ->> 'token'
    into v_active_qr_token
    from public.qr_aktif as q
    where q.id::text = '1'
    limit 1;

    if v_active_qr_token is null
       or btrim(v_active_qr_token) = '' then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Token QR aktif belum tersedia.'
        );
    end if;

    if btrim(v_active_qr_token)
       is distinct from v_qr_payload then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            null,
            p_is_mock,
            'Token QR Code sudah tidak aktif.'
        );
    end if;

    v_distance_meters :=
        2.0 * 6371000.0 * asin(
            sqrt(
                least(
                    1.0,
                    power(
                        sin(
                            radians(
                                p_latitude -
                                v_config.office_latitude
                            ) / 2.0
                        ),
                        2
                    )
                    +
                    cos(
                        radians(
                            v_config.office_latitude
                        )
                    )
                    *
                    cos(
                        radians(p_latitude)
                    )
                    *
                    power(
                        sin(
                            radians(
                                p_longitude -
                                v_config.office_longitude
                            ) / 2.0
                        ),
                        2
                    )
                )
            )
        );

    if v_distance_meters >
       v_config.geofence_radius_meters then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            v_distance_meters,
            p_is_mock,
            format(
                'Anda berada di luar area kantor. Jarak saat ini sekitar %s meter.',
                round(v_distance_meters)::bigint
            )
        );
    end if;

    select l.tipe_log
    into v_last_today_type
    from public.log_presensi as l
    where l.id_teknisi = v_staff.id
      and timezone(
            'Asia/Pontianak',
            l.waktu_log
          )::date =
          timezone(
            'Asia/Pontianak',
            now()
          )::date
    order by
        l.waktu_log desc,
        l.id_absen desc
    limit 1;

    if v_last_today_type is null
       and v_attendance_type <> 'MASUK' then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            v_distance_meters,
            p_is_mock,
            'Anda harus melakukan presensi masuk terlebih dahulu.'
        );
    end if;

    if v_last_today_type = 'MASUK'
       and v_attendance_type <> 'PULANG' then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            v_distance_meters,
            p_is_mock,
            'Presensi masuk hari ini sudah tercatat.'
        );
    end if;

    if v_last_today_type = 'PULANG' then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            v_distance_meters,
            p_is_mock,
            'Presensi hari ini sudah selesai.'
        );
    end if;

    insert into public.qr_token_claims (
        qr_token,
        technician_id,
        attendance_type,
        claimed_at
    )
    values (
        v_qr_payload,
        v_staff.id::text,
        v_attendance_type,
        clock_timestamp()
    )
    on conflict (
        qr_token,
        technician_id
    )
    do nothing;

    get diagnostics
        v_claimed_count = row_count;

    if v_claimed_count = 0 then
        return public.bti_reject_attendance_request(
            v_staff.id::text,
            p_device_id,
            v_attendance_type,
            v_qr_payload,
            p_latitude,
            p_longitude,
            p_accuracy_meters,
            p_location_age_ms,
            v_distance_meters,
            p_is_mock,
            'Token QR Code ini sudah pernah digunakan.'
        );
    end if;

    insert into public.log_presensi (
        id_teknisi,
        waktu_log,
        tipe_log,
        latitude_aktual,
        longitude_aktual,
        is_valid
    )
    values (
        v_staff.id,
        clock_timestamp(),
        v_attendance_type,
        p_latitude,
        p_longitude,
        true
    )
    returning
        id_absen::text,
        waktu_log
    into
        v_attendance_id,
        v_attendance_time;

    insert into public.presensi_audit (
        technician_id,
        attendance_id,
        device_id,
        attendance_type,
        qr_token,
        latitude,
        longitude,
        accuracy_meters,
        location_age_ms,
        distance_meters,
        is_mock,
        result,
        reason,
        request_payload
    )
    values (
        v_staff.id::text,
        v_attendance_id,
        p_device_id,
        v_attendance_type,
        v_qr_payload,
        p_latitude,
        p_longitude,
        p_accuracy_meters,
        p_location_age_ms,
        v_distance_meters,
        p_is_mock,
        'ACCEPTED',
        'Presensi diterima.',
        jsonb_build_object(
            'p_technician_id',
            v_staff.id::text,
            'p_attendance_type',
            v_attendance_type,
            'p_location_age_ms',
            p_location_age_ms
        )
    );

    return jsonb_build_object(
        'success',
        true,
        'accepted',
        true,
        'message',
        case
            when v_attendance_type = 'MASUK'
                then 'Presensi masuk berhasil.'
            else 'Presensi pulang berhasil.'
        end,
        'id',
        v_attendance_id,
        'id_absen',
        v_attendance_id,
        'tipe_log',
        v_attendance_type,
        'waktu_log',
        v_attendance_time,
        'latitude_aktual',
        p_latitude,
        'longitude_aktual',
        p_longitude,
        'accuracy_meters',
        p_accuracy_meters,
        'distance_meters',
        v_distance_meters,
        'is_valid',
        true
    );
end;
$function$;


