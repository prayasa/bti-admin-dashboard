-- ============================================================
-- RPC 1: LOGIN
--
-- Android request:
-- p_nik
-- p_password
-- p_device_id
--
-- Android response:
-- id
-- nama_lengkap
-- nik
-- device_verified
-- ============================================================

create or replace function public.staff_login(
    p_nik text,
    p_password text,
    p_device_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $function$
declare
    v_staff public.teknisi%rowtype;
    v_nik text;
    v_device_id text;
begin
    v_nik := nullif(
        upper(btrim(coalesce(p_nik, ''))),
        ''
    );

    v_device_id := nullif(
        btrim(coalesce(p_device_id, '')),
        ''
    );

    if v_nik is null then
        raise exception
            'NIK wajib diisi.'
            using errcode = 'P0001';
    end if;

    if p_password is null
       or p_password = '' then
        raise exception
            'Password wajib diisi.'
            using errcode = 'P0001';
    end if;

    if v_device_id is null then
        raise exception
            'Identitas perangkat tidak tersedia.'
            using errcode = 'P0001';
    end if;

    select t.*
    into v_staff
    from public.teknisi as t
    where upper(btrim(t.nik)) = v_nik
    limit 1;

    if not found then
        raise exception
            'NIK atau password salah.'
            using errcode = 'P0001';
    end if;

    if v_staff.password is null
       or v_staff.password <> crypt(
            p_password,
            v_staff.password
       ) then
        raise exception
            'NIK atau password salah.'
            using errcode = 'P0001';
    end if;

    if v_staff.device_id is not null
       and btrim(v_staff.device_id) <> ''
       and btrim(v_staff.device_id)
           is distinct from v_device_id then
        raise exception
            'Akun ini telah terikat pada perangkat lain. Hubungi administrator untuk mereset perangkat.'
            using errcode = 'P0001';
    end if;

    if v_staff.device_id is null
       or btrim(v_staff.device_id) = '' then
        update public.teknisi
        set device_id = v_device_id
        where id = v_staff.id
        returning *
        into v_staff;
    end if;

    return jsonb_build_object(
        'success',
        true,
        'message',
        'Login berhasil.',
        'id',
        v_staff.id::text,
        'nik',
        v_staff.nik,
        'nama_lengkap',
        v_staff.nama_lengkap,
        'device_id',
        v_staff.device_id,
        'device_verified',
        true
    );
end;
$function$;


